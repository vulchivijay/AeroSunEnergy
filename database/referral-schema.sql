CREATE TABLE IF NOT EXISTS solar_referrals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_code CHAR(20) COLLATE "C" NOT NULL,
  referrer_name VARCHAR(100) NOT NULL,
  referrer_phone CHAR(10) COLLATE "C" NOT NULL,
  referred_name VARCHAR(100) NOT NULL,
  referred_phone CHAR(10) COLLATE "C" NOT NULL,
  postal_code CHAR(6) COLLATE "C" NOT NULL,
  property_type VARCHAR(24) NOT NULL
    CHECK (property_type IN ('house', 'apartment', 'commercial', 'other')),
  status VARCHAR(24) NOT NULL DEFAULT 'new',
  referrer_permission_confirmed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_solar_referrals_reference_code UNIQUE (reference_code)
);

CREATE INDEX IF NOT EXISTS ix_solar_referrals_status_created_at
  ON solar_referrals (status, created_at);

DROP TRIGGER IF EXISTS trg_solar_referrals_updated_at ON solar_referrals;
CREATE TRIGGER trg_solar_referrals_updated_at
  BEFORE UPDATE ON solar_referrals
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
