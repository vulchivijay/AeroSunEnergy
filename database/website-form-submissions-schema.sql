CREATE TABLE IF NOT EXISTS website_form_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_code CHAR(20) COLLATE "C" NOT NULL,
  form_type VARCHAR(32) COLLATE "C" NOT NULL,
  payload JSONB NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'new',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_website_form_submissions_reference_code UNIQUE (reference_code)
);

CREATE INDEX IF NOT EXISTS ix_website_form_submissions_type_status_created
  ON website_form_submissions (form_type, status, created_at);

DROP TRIGGER IF EXISTS trg_website_form_submissions_updated_at ON website_form_submissions;
CREATE TRIGGER trg_website_form_submissions_updated_at
  BEFORE UPDATE ON website_form_submissions
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
